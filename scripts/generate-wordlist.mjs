/**
 * Converts public/wordlist.txt (ENABLE word list, public domain) into a TypeScript
 * module that can be bundled into Lambda functions via esbuild.
 *
 * Run: node scripts/generate-wordlist.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const wordlistPath = join(root, 'public', 'wordlist.txt');
const outputPath = join(root, 'amplify', 'functions', 'shared', 'wordlist-data.ts');

// Read and normalize the word list
const raw = readFileSync(wordlistPath, 'utf-8');
const words = raw
  .split('\n')
  .map((w) => w.trim().toUpperCase())
  .filter(Boolean);

// Ensure single letters A and I are present (required by PRD)
if (!words.includes('A')) words.push('A');
if (!words.includes('I')) words.push('I');

// Deduplicate
const unique = [...new Set(words)];

// Generate the TypeScript module
const output = `/**
 * AUTO-GENERATED by scripts/generate-wordlist.mjs
 * Source: ENABLE word list (public domain)
 * Words: ${unique.length.toLocaleString()}
 *
 * DO NOT EDIT THIS FILE MANUALLY.
 * Run: node scripts/generate-wordlist.mjs
 */

// Newline-separated uppercase word list
export const WORDLIST_RAW = ${JSON.stringify(unique.join('\n'))};
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output, 'utf-8');

console.log(`Generated wordlist-data.ts with ${unique.length.toLocaleString()} words → ${outputPath}`);
