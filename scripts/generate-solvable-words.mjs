/**
 * Finds all solvable 8-letter words in the ENABLE dictionary and writes them
 * to amplify/functions/shared/solvable-words.ts as a pre-computed pool.
 *
 * A word is "solvable" if BFS can find a path of valid dictionary words
 * formed by removing one letter at a time, ending at a 2-letter word.
 *
 * Run: node scripts/generate-solvable-words.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const wordlistPath = join(root, 'public', 'wordlist.txt');

// Load dictionary
const raw = readFileSync(wordlistPath, 'utf-8');
const allWords = raw
  .split('\n')
  .map((w) => w.trim().toUpperCase())
  .filter(Boolean);

const dictionary = new Set(allWords);
dictionary.add('A');
dictionary.add('I');

// Get all 8-letter words
const eightLetterWords = allWords.filter((w) => w.length === 8);
console.log(`Found ${eightLetterWords.length} eight-letter words to test...`);

/**
 * BFS validator — same logic as amplify/functions/shared/validator.ts
 */
function isSolvable(word) {
  if (!dictionary.has(word)) return false;

  const queue = [word];
  const visited = new Set([word]);

  while (queue.length > 0) {
    const current = queue.shift();

    for (let i = 0; i < current.length; i++) {
      const neighbor = current.slice(0, i) + current.slice(i + 1);
      if (visited.has(neighbor)) continue;
      visited.add(neighbor);
      if (!dictionary.has(neighbor)) continue;

      if (neighbor.length === 2) return true;
      queue.push(neighbor);
    }
  }

  return false;
}

// Test every 8-letter word
const solvable = [];
let tested = 0;

for (const word of eightLetterWords) {
  if (isSolvable(word)) {
    solvable.push(word);
  }
  tested++;
  if (tested % 1000 === 0) {
    process.stdout.write(`\r  Tested ${tested}/${eightLetterWords.length} (${solvable.length} solvable so far)`);
  }
}

console.log(`\n\nFound ${solvable.length} solvable 8-letter words out of ${eightLetterWords.length} total.`);

// Sort alphabetically for stable output
solvable.sort();

// Generate TypeScript module
const outputPath = join(root, 'amplify', 'functions', 'shared', 'solvable-words.ts');

const lines = [];
for (let i = 0; i < solvable.length; i += 6) {
  const chunk = solvable.slice(i, i + 6).map((w) => `'${w}'`).join(', ');
  lines.push(`  ${chunk},`);
}

const output = `/**
 * AUTO-GENERATED by scripts/generate-solvable-words.mjs
 * Source: ENABLE word list — all 8-letter words with a valid BFS solution path
 * Count: ${solvable.length}
 *
 * DO NOT EDIT THIS FILE MANUALLY.
 * Run: node scripts/generate-solvable-words.mjs
 */

export const SOLVABLE_8_LETTER_WORDS: string[] = [
${lines.join('\n')}
];
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output, 'utf-8');

console.log(`Generated solvable-words.ts with ${solvable.length} words → ${outputPath}`);
